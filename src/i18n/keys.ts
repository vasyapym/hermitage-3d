/**
 * i18n key union. Implements the adopted i18n/notes design: "Strings live in a typed
 * dictionary with identical key sets" (language model), the round-24a key-set rules
 * (flat camelCase keys grouped by prefix: chrome. / caption. / notes. / data.), and the
 * literals fence (HUD prose, spec-audit Issue messages, paths, format-law renderings and
 * the stop-id joiner deliberately have no key here).
 *
 * Interpolation tokens are written {name} and resolved by format() in ./format.ts. Token
 * names are stable across languages: the RU column re-orders tokens, never renames them.
 * Column heads are table-scoped (one key per table) so a translation may differ by table.
 */

